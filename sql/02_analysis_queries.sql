-- Query 1: Basic Library Overview

SELECT
    COUNT(*) AS total_transactions,
    COUNT(DISTINCT book_id) AS books_borrowed,
    COUNT(DISTINCT borrower_id) AS active_borrowers,
    SUM(fine) AS total_fines,
    AVG(fine) AS average_fine
FROM borrow_transactions;


-- Query 2: Most Borrowed Books

SELECT
    b.book_id,
    b.title,
    b.category,
    COUNT(t.borrow_id) AS borrow_count
FROM books b
JOIN borrow_transactions t
    ON b.book_id = t.book_id
GROUP BY
    b.book_id,
    b.title,
    b.category
ORDER BY
    borrow_count DESC;


-- Query 3: Borrowings by Category

SELECT
    b.category,
    COUNT(t.borrow_id) AS borrow_count
FROM books b
JOIN borrow_transactions t
    ON b.book_id = t.book_id
GROUP BY
    b.category
ORDER BY
    borrow_count DESC;


-- Query 4: Most Active Borrowers

SELECT
    br.borrower_id,
    br.borrower_name,
    COUNT(t.borrow_id) AS borrow_count
FROM borrowers br
JOIN borrow_transactions t
    ON br.borrower_id = t.borrower_id
GROUP BY
    br.borrower_id,
    br.borrower_name
ORDER BY
    borrow_count DESC;


-- Query 5: Returned vs Not Returned

SELECT
    CASE
        WHEN returned = 1 THEN 'Returned'
        ELSE 'Not Returned'
    END AS return_status,
    COUNT(*) AS transaction_count
FROM borrow_transactions
GROUP BY returned;

 -- Query 6 :Find the total fines, average fine, maximum fine, and number of transactions that generated a fine.

 SELECT
    SUM(fine) As Total_Fine,
    AVG(fine) AS Average_Fine,
    MAX(fine) AS Max_Fine,
    count(fine) AS NO_Trans
FROM borrow_transactions
WHERE fine > 0;

--Query 7 : ind how many transactions are: Returned , Not returned  And calculate the percentage of total transactions for each.

SELECT
    CASE
        WHEN return_date IS NULL THEN 'Not returned'
        ELSE 'Returned'
    END AS status,
    COUNT(*) AS transaction_count,
    ROUND(COUNT(*) * 100.0 / (SELECT COUNT(*) FROM borrow_transactions), 2) AS percentage
FROM borrow_transactions
GROUP BY
    CASE
        WHEN return_date IS NULL THEN 'Not returned'
        ELSE 'Returned'
    END;


-- Query 8 : Fine by Category , Find the total fine generated by each book category.

SELECT
    b.category,
    SUM(bt.fine_amount) AS total_fine,
    AVG(bt.fine_amount) AS average_fine
FROM books AS b
JOIN borrow_transactions AS bt
    ON b.book_id = bt.book_id
GROUP BY b.category
ORDER BY total_fine DESC;


--Query 9 — Monthly Borrowing Trend , Find the number of borrowing transactions for each month based on borrow_date.

SELECT
    DATE_FORMAT(borrow_date, '%Y-%m') AS month,
    COUNT(*) AS borrow_count
FROM borrow_transactions
GROUP BY DATE_FORMAT(borrow_date, '%Y-%m')
ORDER BY month;

--Query 10 — Most Borrowed Authors, Find the 10 authors whose books have been borrowed the most.

SELECT
    b.author,
    COUNT(*) AS borrow_count
FROM books AS b
JOIN borrow_transactions AS bt
    ON b.book_id = bt.book_id
GROUP BY b.author
ORDER BY borrow_count DESC
LIMIT 10;

--Query 11 : Borrowing Trend by Category and Find the number of borrowings for each category in each month.

SELECT
    DATE_FORMAT(bt.borrow_date, '%Y-%m') AS month,
    b.category,
    COUNT(*) AS borrow_count
FROM books AS b
JOIN borrow_transactions AS bt
    ON b.book_id = bt.book_id
GROUP BY
    DATE_FORMAT(bt.borrow_date, '%Y-%m'),
    b.category
ORDER BY
    month ASC,
    b.category ASC;

--Query 12 : Find the 10 least-borrowed books in the library.

SELECT
    b.book_id,
    b.title,
    b.category,
    COUNT(bt.book_id) AS borrow_count
FROM books AS b
LEFT JOIN borrow_transactions AS bt
    ON b.book_id = bt.book_id
GROUP BY
    b.book_id,
    b.title,
    b.category
ORDER BY borrow_count ASC
LIMIT 10;

--Query 13 : Find the 10 borrowers who generated the highest total fines.

SELECT
    b.borrower_id,
    b.borrower_name,
    SUM(bt.fine) AS total_fine,
    COUNT(*) AS transaction_count
FROM borrowers AS b
JOIN borrow_transactions AS bt
    ON b.borrower_id = bt.borrower_id
GROUP BY
    b.borrower_id,
    b.borrower_name
ORDER BY total_fine DESC
LIMIT 10;

--Query 14 : Find the overall borrowing and fine performance of each book category.

SELECT
    b.category,
    COUNT(*) AS borrow_count,
    SUM(bt.fine) AS total_fine,
    AVG(bt.fine) AS average_fine
FROM books AS b
JOIN borrow_transactions AS bt
    ON b.book_id = bt.book_id
GROUP BY b.category
ORDER BY borrow_count DESC;

--Query 15 : create a single-row summary of the key library metrics for the dashboard.

SELECT
    (SELECT COUNT(*) FROM borrow_transactions) AS total_transactions,
    (SELECT COUNT(*) FROM books) AS total_books,
    (SELECT COUNT(*) FROM borrowers) AS total_borrowers,

    (SELECT COUNT(*)
     FROM borrow_transactions
     WHERE return_date IS NOT NULL) AS returned_transactions,

    (SELECT COUNT(*)
     FROM borrow_transactions
     WHERE return_date IS NULL) AS not_returned_transactions,

    (SELECT SUM(fine)
     FROM borrow_transactions) AS total_fine,

    (SELECT AVG(fine)
     FROM borrow_transactions) AS average_fine;

